import jax
from craftax.craftax.constants import Achievement, ItemType
from minicraftax.craftax_state import TaskParams
from minicraftax.tasks.base_task import BaseTask
from minicraftax.world_builder import WorldBuilder


class Env(BaseTask):
    def __init__(self, sp, p):
        super().__init__(sp, p)
        self.relevant_achievements = [Achievement.DEFEAT_KOBOLD]
        self.completed_achievements = []
        self.label = "DEFEAT_KOBOLD"

    def get_task_params(self):
        return TaskParams(needs_depletion_multiplier=0.3)

    def generate_world(self, rng):
        rng, _r = jax.random.split(rng)
        b = WorldBuilder(_r, self.static_params, self.params)
        b.set_starting_floor(2)
        b.set_monsters_killed(2, 8)
        b.set_player_inventory({
            "wood": 7, "stone": 27, "coal": 3, "iron": 3, "sapling": 1,
            "pickaxe": 3, "sword": 3, "bow": 1, "arrows": 7, "torches": 10,
        })
        s = b.build(rng)
        up = b.ladders_up[2]
        return s.replace(item_map=s.item_map.at[2, up[0], up[1]].set(ItemType.NONE.value))
